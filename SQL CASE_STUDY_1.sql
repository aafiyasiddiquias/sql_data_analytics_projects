--13. What is the total sales done on date 2010-01-01?
	SELECT sum(Sales) AS Total_Sales FROM Fact WHERE Date = '2010-01-01';

--14. Display the average total expense of each product ID on an individual date.
	SELECT Date, ProductID, avg(Total_Expenses) AS Average_Expense FROM fact GROUP BY Date, ProductID ORDER BY Date, ProductID;

--15. Display the table with the following attributes such as date, productID, product_type, product, sales, profit, state, area_code.
	SELECT f.Date, f.ProductID, P.Product_Type, P.Product, f.Sales, f.Profit, L.State, f.Area_Code FROM fact f
	JOIN Product P ON f.ProductID = P.ProductID
	JOIN Location L ON f.Area_Code = L.Area_Code;

--16. Display the rank without any gap to show the sales wise rank.
	SELECT *, DENSE_RANK() over (ORDER BY Sales DESC) AS Sales_Rank FROM fact;

--17. Find the state wise profit and sales.
	SELECT L.State, sum(f.Profit) AS Total_Profit, sum(f.Sales) AS Total_Sales
	FROM fact AS f
	JOIN Location AS L ON f.Area_Code = L.Area_Code
	GROUP BY L.State;

--18. Find the state wise profit and sales along with the product name.
	SELECT L.State, P.Product, sum(f.Profit) AS Total_Profit, sum(f.Sales) AS Total_Sales
	FROM fact AS f
	JOIN Location AS L ON f.Area_Code = L.Area_Code
	JOIN Product AS P ON f.Productid = P.Productid
	GROUP BY L.State, P.Product;
--19. If there is an increase in sales of 5%, calculate the increased sales.
	SELECT ProductID, Sales, Sales * 1.05 AS Increased_Sales FROM fact;

--20. Find the maximum profit along with the product ID and product type.
	SELECT f.ProductID, P.Product_Type, f.Profit
	FROM fact AS f
	JOIN Product AS P ON f.ProductID = P.ProductID
	WHERE f.Profit = (SELECT Max(Profit) FROM fact);

--21. Create a stored procedure to fetch the result according to the product type from Product Table.
	CREATE PROCEDURE ProductsByType
    @ProductType VARCHAR(50)
	AS
	BEGIN
		SELECT *
		FROM Product
		WHERE Product_Type = @ProductType;
	END;

	EXEC ProductsByType 'Coffee';

--22. Write a query by creating a condition in which if the total expenses is less than 60 then it is a profit or else loss.
	SELECT *, 
	CASE WHEN Total_Expenses < 60 THEN 'Profit' ELSE 'Loss'
    END AS Result
	FROM fact;

--23. Give the total weekly sales value with the date and product ID details. Use roll-up to pull the data in hierarchical order.
	SELECT DATEPART(WEEK, Date) AS Week_No, Date, ProductId, sum(Sales) AS Total_Weekly_Sales
	FROM fact
	GROUP BY ROLLUP
	(
		DATEPART(WEEK, Date),
		Date,
		ProductId
	)
	ORDER BY
		Week_No,
		Date,
		ProductId;


--25. Create a user-defined function for the product table to fetch a particular product type based upon the user’s preference.
	CREATE FUNCTION user_preference
	(
		@PPT VARCHAR(50)
	)
	RETURNS TABLE
	AS
	RETURN
	(
		SELECT *
		FROM Product
		WHERE Product_Type = @PPT
	);

	SELECT * from user_preference ('Coffee');


